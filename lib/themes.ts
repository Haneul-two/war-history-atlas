export function getTheme(id: string) {
  return themes.find((t) => t.id === id);
}
export function themesForWar(id: string) {
  return themes.filter((t) => t.stops.some((s) => s.warId === id));
}
export function parseStep(value: string | null | undefined) {
  return value && /^[1-4]$/.test(value) ? Number(value) - 1 : 0;
}
