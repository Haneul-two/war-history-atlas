export function recordsForWar(id: string) {
  return archiveRecords.filter((r) => r.warId === id);
}
export function filterRecords(kind: string, warId: string) {
  return archiveRecords.filter(
    (r) =>
      (kind === 'all' || r.kind === kind) &&
      (warId === 'all' || r.warId === warId),
  );
}
